---DATOS DE LA LINEA DEL RUBRO
SELECT 
    PR_ACUMULADO.VIGENCIA,
    PR_ACUMULADO.CODIGO_COMPANIA,
    PR_ACUMULADO.CODIGO_UNIDAD_EJECUTORA,
    PR_ACUMULADO.INTERNO,
    PR_ACUMULADO.NDOC,
    PR_ACUMULADO.VCMPRMSO,
    PR_ACUMULADO.VATRZCION,
    PR_ACUMULADO.VANULAUTORI,
    PR_ACUMULADO.VANULPARCOMP,
    PR_ACUMULADO.VANULCOMP,
    PR_ACUMULADO.VSALDORP,
    PR_ACUMULADO.CADENA,
    PR_ACUMULADO.DESCRIPCION,
    PR_ACUMULADO.VALOR_ORDENES_DE_PAGO,
	 PR_MES.VALOR_MES
FROM
( SELECT
    PR_UNION.VIGENCIA,
    PR_UNION.CODIGO_COMPANIA,
    PR_UNION.CODIGO_UNIDAD_EJECUTORA,
    PR_UNION.INTERNO,
    PR_UNION.NDOC,
    PR_UNION.VCMPRMSO,
    PR_UNION.VATRZCION,
    PR_UNION.VANULAUTORI,
    PR_UNION.VANULPARCOMP,
    PR_UNION.VANULCOMP,
    PR_UNION.VSALDORP,
(CODIGO_NIVEL1||'-'||CODIGO_NIVEL2||'-'||CODIGO_NIVEL3||'-'||CODIGO_NIVEL4||'-'||CODIGO_NIVEL5||'-'||CODIGO_NIVEL6||'-'||CODIGO_NIVEL7||'-'||CODIGO_NIVEL8) CADENA,
    DESCRIPCION,
    ORDENES.VALOR_ORDENES_DE_PAGO
FROM 
    (
      SELECT
      PR.VIGENCIA,
      PR.CODIGO_COMPANIA,
      CODIGO_UNIDAD_EJECUTORA,
      PR_RUBRO.INTERNO,
      NDOC,
      SUM(VCMPRMSO) VCMPRMSO,
      SUM(VATRZCION) VATRZCION,
      SUM(VANULAUTORI) VANULAUTORI,
      SUM(VANULPARCOMP) VANULPARCOMP,
      SUM(VANULCOMP) VANULCOMP,
      (SUM(VCMPRMSO) + SUM(VANULCOMP) + SUM(VANULPARCOMP) - (SUM(VATRZCION)+SUM(VANULAUTORI))) VSALDORP,
      PR_NIVEL1.CODIGO CODIGO_NIVEL1,
      PR_NIVEL2.CODIGO CODIGO_NIVEL2,
      PR_NIVEL3.CODIGO CODIGO_NIVEL3,
      PR_NIVEL4.CODIGO CODIGO_NIVEL4,
      PR_NIVEL5.CODIGO CODIGO_NIVEL5,
      PR_NIVEL6.CODIGO CODIGO_NIVEL6,
      PR_NIVEL7.CODIGO CODIGO_NIVEL7,
      PR_NIVEL8.CODIGO CODIGO_NIVEL8,
      PR_RUBRO.DESCRIPCION
      FROM
      (SELECT
      DE.VIGENCIA VIGENCIA,
      DE.CODIGO_COMPANIA CODIGO_COMPANIA,
      DE.CODIGO_UNIDAD_EJECUTORA CODIGO_UNIDAD_EJECUTORA,
      DE.RUBRO_INTERNO INTERNO,
      'COM' TIPO,
      2 ORDEN,
      MA.FECHA_REGISTRO FECHA,
      TO_CHAR( MA.NUMERO_REGISTRO )
       NDOC,
      MA.TIPO_COMPROMISO || '-'
      || TO_CHAR( MA.NUMERO_COMPROMISO )
      || '-' || CO.OBJETO
       DETALLE,
      0 CONSECUTIVO_ORDEN,
      DE.VALOR VCMPRMSO,
      0 VATRZCION,
      0 VANULAUTORI,
      0 VANULPARCOMP,
      0 VANULCOMP
      FROM
      PR_REGISTRO_DISPONIBILIDAD DE,
      PR_REGISTRO_PRESUPUESTAL MA,
      PR_COMPROMISOS CO
      WHERE
	      DE.VIGENCIA = MA.VIGENCIA
      AND DE.CODIGO_COMPANIA = MA.CODIGO_COMPANIA
      AND DE.CODIGO_UNIDAD_EJECUTORA = MA.CODIGO_UNIDAD_EJECUTORA
      AND DE.NUMERO_REGISTRO = MA.NUMERO_REGISTRO
      AND DE.NUMERO_DISPONIBILIDAD = MA.NUMERO_DISPONIBILIDAD
      AND MA.VIGENCIA = CO.VIGENCIA
      AND MA.CODIGO_COMPANIA = CO.CODIGO_COMPANIA
      AND MA.CODIGO_UNIDAD_EJECUTORA = CO.CODIGO_UNIDAD_EJECUTORA
      AND MA.NUMERO_REGISTRO = CO.NUMERO_REGISTRO
      AND MA.NUMERO_COMPROMISO = CO.NUMERO_COMPROMISO
      AND MA.TIPO_COMPROMISO = CO.TIPO_COMPROMISO
      AND DE.VIGENCIA = ( :P_VIGENCIA - 1)
      AND DE.CODIGO_COMPANIA = :P_COMPANIA
      AND DE.CODIGO_UNIDAD_EJECUTORA = :P_UNIDAD
      AND DE.RUBRO_INTERNO = NVL(:P_RUBRO_INTERNO,DE.RUBRO_INTERNO)
      UNION
      SELECT
      DE.VIGENCIA VIGENCIA,
      DE.CODIGO_COMPANIA CODIGO_COMPANIA,
      DE.CODIGO_UNIDAD_EJECUTORA CODIGO_UNIDAD_EJECUTORA,
      DE.RUBRO_INTERNO INTERNO,
      'OPA' TIPO,
      3 ORDEN,
      MA.FECHA_REGISTRO FECHA,
      TO_CHAR( MA.NUMERO_REGISTRO )
       NDOC,
      MA.OBJETO DETALLE,
      MA.CONSECUTIVO_ORDEN CONSECUTIVO_ORDEN,
      0 VCMPRMSO,
      DE.VALOR VATRZCION,
      0 VANULAUTORI,
      0 VANULPARCOMP,
      0 VANULCOMP
      FROM
      PR_ORDEN_DE_PAGO_REGISTRO DE,
      PR_ORDEN_DE_PAGO MA
      WHERE
          DE.VIGENCIA = MA.VIGENCIA
      AND DE.CODIGO_COMPANIA = MA.CODIGO_COMPANIA
      AND DE.CODIGO_UNIDAD_EJECUTORA = MA.CODIGO_UNIDAD_EJECUTORA
      AND DE.NUMERO_DISPONIBILIDAD = MA.NUMERO_DISPONIBILIDAD
      AND DE.NUMERO_REGISTRO = MA.NUMERO_REGISTRO
      AND DE.NUMERO_ORDEN = MA.NUMERO_ORDEN
      AND DE.CONSECUTIVO_ORDEN = MA.CONSECUTIVO_ORDEN
      AND DE.VIGENCIA = (:P_VIGENCIA-1)
      AND DE.CODIGO_COMPANIA = :P_COMPANIA
      AND DE.CODIGO_UNIDAD_EJECUTORA = :P_UNIDAD
      AND DE.RUBRO_INTERNO = NVL(:P_RUBRO_INTERNO,DE.RUBRO_INTERNO)
      AND TO_CHAR(MA.FECHA_REGISTRO,'YYYY') = DE.VIGENCIA
      UNION
      SELECT
      VIGENCIA VIGENCIA,
      CODIGO_COMPANIA CODIGO_COMPANIA,
      CODIGO_UNIDAD_EJECUTORA CODIGO_UNIDAD_EJECUTORA,
      RUBRO_INTERNO INTERNO,
      'ANU' TIPO,
      7 ORDEN,
      FECHA_ANULACION FECHA,
      TO_CHAR(NUMERO_REGISTRO) NDOC,
      MOTIVO DETALLE,
      CONSECUTIVO_ANULACION CONSECUTIVO_ORDEN,
      0 VCMPRMSO,
      0 VATRZCION,
      0 VANULAUTORI,
      -VALOR_ANULADO VANULPARCOMP,
      0 VANULCOMP
      FROM
      PR_RP_ANULADOS
      WHERE
      VIGENCIA = (:P_VIGENCIA-1)
      AND CODIGO_COMPANIA = :P_COMPANIA
      AND CODIGO_UNIDAD_EJECUTORA = :P_UNIDAD
      AND RUBRO_INTERNO = NVL(:P_RUBRO_INTERNO, RUBRO_INTERNO)
      UNION
      SELECT
      DE.VIGENCIA VIGENCIA,
      DE.CODIGO_COMPANIA CODIGO_COMPANIA,
      DE.CODIGO_UNIDAD_EJECUTORA CODIGO_UNIDAD_EJECUTORA,
      DE.RUBRO_INTERNO INTERNO,
      'ANT' TIPO,
      10 ORDEN,
      AN.FECHA_REGISTRO FECHA,
      TO_CHAR(DE.NUMERO_REGISTRO) NDOC,
      'OPA-' || TO_CHAR( DE.NUMERO_ORDEN )
      || '-' || AN.DESCRIPCION DETALLE,
      AN.CONSECUTIVO_ORDEN CONSECUTIVO_ORDEN,
      0 VCMPRMSO,
      0 VATRZCION,
      -DE.VALOR VANULAUTORI,
      0 VANULPARCOMP,
      0 VANULCOMP
      FROM
      (SELECT
      VIGENCIA,
      CODIGO_COMPANIA,
      CODIGO_UNIDAD_EJECUTORA,
      FECHA_REGISTRO,
      NUMERO_DOCUMENTO_ANULADO,
      NUMERO_REGISTRO,
      CONSECUTIVO_ORDEN,
      NUMERO_OFICIO,
      DESCRIPCION
      FROM
      PR_ANULACIONES
      WHERE
      VIGENCIA = (:P_VIGENCIA-1)
      AND CODIGO_COMPANIA = :P_COMPANIA
      AND CODIGO_UNIDAD_EJECUTORA = :P_UNIDAD
      AND DOCUMENTO_ANULADO = 'ORDEN'
      ) AN,
      PR_ORDEN_DE_PAGO_REGISTRO DE
      WHERE
      AN.VIGENCIA = DE.VIGENCIA
      AND AN.CODIGO_COMPANIA = DE.CODIGO_COMPANIA
      AND AN.CODIGO_UNIDAD_EJECUTORA = DE.CODIGO_UNIDAD_EJECUTORA
      AND AN.NUMERO_REGISTRO = DE.NUMERO_REGISTRO
      AND AN.NUMERO_DOCUMENTO_ANULADO = DE.NUMERO_ORDEN
      AND AN.CONSECUTIVO_ORDEN = DE.CONSECUTIVO_ORDEN
      AND AN.VIGENCIA = (:P_VIGENCIA-1)
      AND AN.CODIGO_COMPANIA = :P_COMPANIA
      AND AN.CODIGO_UNIDAD_EJECUTORA = :P_UNIDAD
      AND DE.RUBRO_INTERNO = NVL(:P_RUBRO_INTERNO,DE.RUBRO_INTERNO)
      UNION
      -- SE INCLUYE AJUSTE 29/01/2004
      SELECT
      MA.VIGENCIA VIGENCIA,
      MA.CODIGO_COMPANIA CODIGO_COMPANIA,
      MA.CODIGO_UNIDAD_EJECUTORA CODIGO_UNIDAD_EJECUTORA,
      DE.RUBRO_INTERNO INTERNO,
      'AJT' TIPO,
      20 ORDEN,
      MA.FECHA_REGISTRO FECHA,
      TO_CHAR(MA.NUMERO_REGISTRO) NDOC,
      'AJT-' || TO_CHAR( MA.NUMERO_REGISTRO )
      || '-' || MA.DESCRIPCION DETALLE,
      MA.CONSECUTIVO_ORDEN CONSECUTIVO_ORDEN,
      DE.VALOR VCMPRMSO,
      0 VATRZCION,
      0 VANULAUTORI,
      0 VANULPARCOMP,
      0 VANULCOMP
      FROM
      PR_REINTEGRO_AJUSTES_RUBRO DE,
      PR_REINTEGRO_AJUSTES MA
      WHERE DE.VIGENCIA = MA.VIGENCIA
      AND DE.CODIGO_COMPANIA = MA.CODIGO_COMPANIA
      AND DE.CODIGO_UNIDAD_EJECUTORA = MA.CODIGO_UNIDAD_EJECUTORA
      AND DE.NUMERO_ORDEN = MA.NUMERO_ORDEN
      AND DE.CONSECUTIVO_ORDEN = MA.CONSECUTIVO_ORDEN
      AND DE.NUMERO_DISPONIBILIDAD = MA.NUMERO_DISPONIBILIDAD
      AND DE.NUMERO_REGISTRO = MA.NUMERO_REGISTRO
      AND DE.CONSECUTIVO_AJUSTE = MA.CONSECUTIVO_AJUSTE
      AND DE.VIGENCIA = (:P_VIGENCIA-1)
      AND DE.CODIGO_COMPANIA = :P_COMPANIA
      AND DE.CODIGO_UNIDAD_EJECUTORA = :P_UNIDAD
      AND MA.TIPO_MOVIMIENTO = 'RP_AJUSTE'
      AND MA.CERRADO = 9
      AND DE.RUBRO_INTERNO= NVL(:P_RUBRO_INTERNO,DE.RUBRO_INTERNO)
      UNION
      SELECT
      DE.VIGENCIA VIGENCIA,
      DE.CODIGO_COMPANIA CODIGO_COMPANIA,
      DE.CODIGO_UNIDAD_EJECUTORA CODIGO_UNIDAD_EJECUTORA,
      DE.RUBRO_INTERNO INTERNO,
      'ANT' TIPO,
      11 ORDEN,
      AN.FECHA_REGISTRO FECHA,
      TO_CHAR(MA.NUMERO_REGISTRO) NDOC,
      'RP-' || TO_CHAR( MA.NUMERO_REGISTRO )
      || '-' || AN.DESCRIPCION DETALLE,
      0 CONSECUTIVO_ORDEN,
      0 VCMPRMSO,
      0 VATRZCION,
      0 VANULAUTORI,
      0 VANULPARCOMP,
      -DE.VALOR VANULCOMP
      FROM
      (SELECT
      VIGENCIA,
      CODIGO_COMPANIA,
      CODIGO_UNIDAD_EJECUTORA,
      FECHA_REGISTRO,
      NUMERO_DOCUMENTO_ANULADO,
      NUMERO_REGISTRO,
      NUMERO_OFICIO,
      DESCRIPCION
      FROM
      PR_ANULACIONES
      WHERE
      VIGENCIA = ( :P_VIGENCIA-1)
      AND CODIGO_COMPANIA = :P_COMPANIA
      AND CODIGO_UNIDAD_EJECUTORA = :P_UNIDAD
      AND DOCUMENTO_ANULADO = 'REGISTRO'
      ) AN,
      PR_REGISTRO_PRESUPUESTAL MA,
      PR_REGISTRO_DISPONIBILIDAD DE
      WHERE
      AN.VIGENCIA = MA.VIGENCIA
      AND AN.CODIGO_COMPANIA = MA.CODIGO_COMPANIA
      AND AN.CODIGO_UNIDAD_EJECUTORA = MA.CODIGO_UNIDAD_EJECUTORA
      AND AN.NUMERO_DOCUMENTO_ANULADO = MA.NUMERO_REGISTRO
      AND MA.VIGENCIA = DE.VIGENCIA
      AND MA.CODIGO_COMPANIA = DE.CODIGO_COMPANIA
      AND MA.CODIGO_UNIDAD_EJECUTORA = DE.CODIGO_UNIDAD_EJECUTORA
      AND MA.NUMERO_REGISTRO = DE.NUMERO_REGISTRO
      AND MA.NUMERO_DISPONIBILIDAD = DE.NUMERO_DISPONIBILIDAD
      AND AN.VIGENCIA = ( :P_VIGENCIA-1)
      AND AN.CODIGO_COMPANIA = :P_COMPANIA
      AND AN.CODIGO_UNIDAD_EJECUTORA = :P_UNIDAD
      ) PR, PR_RUBRO,PR_NIVEL1,PR_NIVEL2,PR_NIVEL3,PR_NIVEL4,PR_NIVEL5,PR_NIVEL6,PR_NIVEL7,PR_NIVEL8
      WHERE
      PR.VIGENCIA=PR_RUBRO.VIGENCIA AND
      PR.INTERNO=PR_RUBRO.INTERNO AND
      PR_RUBRO.INTERNO= NVL(:P_RUBRO_INTERNO,PR_RUBRO.INTERNO) AND
      PR_RUBRO.VIGENCIA = PR_NIVEL1.VIGENCIA AND
      PR_RUBRO.INTERNO_NIVEL1 = PR_NIVEL1.INTERNO AND
      PR_RUBRO.TIPO_PLAN = PR_NIVEL1.TIPO_PLAN AND
      PR_RUBRO.VIGENCIA = PR_NIVEL2.VIGENCIA AND
      PR_RUBRO.INTERNO_NIVEL2 = PR_NIVEL2.INTERNO AND
      PR_RUBRO.TIPO_PLAN = PR_NIVEL2.TIPO_PLAN AND
      PR_RUBRO.VIGENCIA = PR_NIVEL3.VIGENCIA AND
      PR_RUBRO.INTERNO_NIVEL3 = PR_NIVEL3.INTERNO AND
      PR_RUBRO.TIPO_PLAN = PR_NIVEL3.TIPO_PLAN AND
      PR_RUBRO.VIGENCIA = PR_NIVEL4.VIGENCIA AND
      PR_RUBRO.INTERNO_NIVEL4 = PR_NIVEL4.INTERNO AND
      PR_RUBRO.TIPO_PLAN = PR_NIVEL4.TIPO_PLAN AND
      PR_RUBRO.VIGENCIA = PR_NIVEL5.VIGENCIA AND
      PR_RUBRO.INTERNO_NIVEL5 = PR_NIVEL5.INTERNO AND
      PR_RUBRO.TIPO_PLAN = PR_NIVEL5.TIPO_PLAN AND
      PR_RUBRO.VIGENCIA = PR_NIVEL6.VIGENCIA AND
      PR_RUBRO.INTERNO_NIVEL6 = PR_NIVEL6.INTERNO AND
      PR_RUBRO.TIPO_PLAN = PR_NIVEL6.TIPO_PLAN AND
      PR_RUBRO.VIGENCIA = PR_NIVEL7.VIGENCIA AND
      PR_RUBRO.INTERNO_NIVEL7 = PR_NIVEL7.INTERNO AND
      PR_RUBRO.TIPO_PLAN = PR_NIVEL7.TIPO_PLAN AND
      PR_RUBRO.VIGENCIA = PR_NIVEL8.VIGENCIA AND
      PR_RUBRO.INTERNO_NIVEL8 = PR_NIVEL8.INTERNO AND
      PR_RUBRO.TIPO_PLAN = PR_NIVEL8.TIPO_PLAN AND
      PR.VIGENCIA = ( :P_VIGENCIA-1) AND
      PR.CODIGO_COMPANIA = :P_COMPANIA AND
      PR.CODIGO_UNIDAD_EJECUTORA = :P_UNIDAD
      GROUP BY PR.VIGENCIA,
      PR.CODIGO_COMPANIA,
      PR.CODIGO_UNIDAD_EJECUTORA,
      PR.NDOC,PR_RUBRO.INTERNO,
      PR_NIVEL1.CODIGO,
      PR_NIVEL2.CODIGO,
      PR_NIVEL3.CODIGO,
      PR_NIVEL4.CODIGO,
      PR_NIVEL5.CODIGO,
      PR_NIVEL6.CODIGO,
      PR_NIVEL7.CODIGO,
      PR_NIVEL8.CODIGO,
      PR_RUBRO.DESCRIPCION
      ) PR_UNION,
    ( 
	  SELECT 
	  NVL(SUM(NVL(pr_orden_de_pago_registro.valor,0)),0) VALOR_ORDENES_DE_PAGO,
	  PR_ORDEN_DE_PAGO_REGISTRO.RUBRO_INTERNO  INTERNO,
	  PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_REGISTRO  NUMERO_REGISTRO
    --SELECT  *
    FROM PR_ORDEN_DE_PAGO_REGISTRO, PR_ORDEN_DE_PAGO 
    WHERE
    NOT EXISTS
    (
	  SELECT NUMERO_DOCUMENTO_ANULADO,NUMERO_REGISTRO,CONSECUTIVO_ORDEN
	  FROM PR_ANULACIONES_RESERVAS
	  WHERE
	  VIGENCIA = PR_ORDEN_DE_PAGO_REGISTRO.VIGENCIA
	  AND CODIGO_COMPANIA = PR_ORDEN_DE_PAGO.CODIGO_COMPANIA
	  AND CODIGO_UNIDAD_EJECUTORA = PR_ORDEN_DE_PAGO.CODIGO_UNIDAD_EJECUTORA
	  AND DOCUMENTO_ANULADO = 'ORDEN'
	  AND NUMERO_DOCUMENTO_ANULADO = PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_ORDEN
    AND NUMERO_REGISTRO = PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_REGISTRO 
	  AND CONSECUTIVO_ORDEN = PR_ORDEN_DE_PAGO_REGISTRO.CONSECUTIVO_ORDEN
    )
    AND PR_ORDEN_DE_PAGO_REGISTRO.VIGENCIA = PR_ORDEN_DE_PAGO.VIGENCIA
    AND PR_ORDEN_DE_PAGO_REGISTRO.CODIGO_COMPANIA = PR_ORDEN_DE_PAGO.CODIGO_COMPANIA
    AND PR_ORDEN_DE_PAGO_REGISTRO.CODIGO_UNIDAD_EJECUTORA = PR_ORDEN_DE_PAGO.CODIGO_UNIDAD_EJECUTORA
    AND PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_DISPONIBILIDAD = PR_ORDEN_DE_PAGO.NUMERO_DISPONIBILIDAD
    AND PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_REGISTRO = PR_ORDEN_DE_PAGO.NUMERO_REGISTRO
    AND PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_ORDEN = PR_ORDEN_DE_PAGO.NUMERO_ORDEN 
    AND PR_ORDEN_DE_PAGO_REGISTRO.CONSECUTIVO_ORDEN = PR_ORDEN_DE_PAGO.CONSECUTIVO_ORDEN
    AND PR_ORDEN_DE_PAGO_REGISTRO.VIGENCIA = :P_VIGENCIA - 1
    AND PR_ORDEN_DE_PAGO_REGISTRO.CODIGO_COMPANIA = :P_COMPANIA
    AND PR_ORDEN_DE_PAGO_REGISTRO.CODIGO_UNIDAD_EJECUTORA = :P_UNIDAD
    AND TO_CHAR(PR_ORDEN_DE_PAGO.FECHA_REGISTRO,'YYYY') = :P_VIGENCIA
    AND TO_NUMBER(TO_CHAR(PR_ORDEN_DE_PAGO.FECHA_REGISTRO, 'MM')) <= :MES --TO_NUMBER(TO_CHAR(:P_FECHA_HASTA,'MM'))
    AND PR_ORDEN_DE_PAGO_REGISTRO.RUBRO_INTERNO = NVL(:P_RUBRO_INTERNO,PR_ORDEN_DE_PAGO_REGISTRO.RUBRO_INTERNO)
	 GROUP BY  PR_ORDEN_DE_PAGO_REGISTRO.RUBRO_INTERNO, PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_REGISTRO
	 ) ORDENES      
WHERE 
   PR_UNION.VSALDORP <> 0
   AND PR_UNION.INTERNO = ORDENES.INTERNO(+)
   AND PR_UNION.NDOC = ORDENES.NUMERO_REGISTRO(+) ) PR_ACUMULADO,
    ( 
	  SELECT 
	  NVL(SUM(NVL(pr_orden_de_pago_registro.valor,0)),0) VALOR_MES,
	  PR_ORDEN_DE_PAGO_REGISTRO.RUBRO_INTERNO  INTERNO,
	  PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_REGISTRO  NUMERO_REGISTRO
    FROM PR_ORDEN_DE_PAGO_REGISTRO, PR_ORDEN_DE_PAGO 
    WHERE
    NOT EXISTS
    (
	  SELECT NUMERO_DOCUMENTO_ANULADO,NUMERO_REGISTRO,CONSECUTIVO_ORDEN
	  FROM PR_ANULACIONES_RESERVAS
	  WHERE
	  VIGENCIA = PR_ORDEN_DE_PAGO_REGISTRO.VIGENCIA
	  AND CODIGO_COMPANIA = PR_ORDEN_DE_PAGO.CODIGO_COMPANIA
	  AND CODIGO_UNIDAD_EJECUTORA = PR_ORDEN_DE_PAGO.CODIGO_UNIDAD_EJECUTORA
	  AND DOCUMENTO_ANULADO = 'ORDEN'
	  AND NUMERO_DOCUMENTO_ANULADO = PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_ORDEN
      AND NUMERO_REGISTRO = PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_REGISTRO 
	  AND CONSECUTIVO_ORDEN = PR_ORDEN_DE_PAGO_REGISTRO.CONSECUTIVO_ORDEN
    )
    AND PR_ORDEN_DE_PAGO_REGISTRO.VIGENCIA = PR_ORDEN_DE_PAGO.VIGENCIA
    AND PR_ORDEN_DE_PAGO_REGISTRO.CODIGO_COMPANIA = PR_ORDEN_DE_PAGO.CODIGO_COMPANIA
    AND PR_ORDEN_DE_PAGO_REGISTRO.CODIGO_UNIDAD_EJECUTORA = PR_ORDEN_DE_PAGO.CODIGO_UNIDAD_EJECUTORA
    AND PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_DISPONIBILIDAD = PR_ORDEN_DE_PAGO.NUMERO_DISPONIBILIDAD
    AND PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_REGISTRO = PR_ORDEN_DE_PAGO.NUMERO_REGISTRO
    AND PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_ORDEN = PR_ORDEN_DE_PAGO.NUMERO_ORDEN 
    AND PR_ORDEN_DE_PAGO_REGISTRO.CONSECUTIVO_ORDEN = PR_ORDEN_DE_PAGO.CONSECUTIVO_ORDEN
    AND PR_ORDEN_DE_PAGO_REGISTRO.VIGENCIA = :P_VIGENCIA - 1
    AND PR_ORDEN_DE_PAGO_REGISTRO.CODIGO_COMPANIA = :P_COMPANIA
    AND PR_ORDEN_DE_PAGO_REGISTRO.CODIGO_UNIDAD_EJECUTORA = :P_UNIDAD
    AND TO_CHAR(PR_ORDEN_DE_PAGO.FECHA_REGISTRO,'YYYY') = :P_VIGENCIA
    AND TO_NUMBER(TO_CHAR(PR_ORDEN_DE_PAGO.FECHA_REGISTRO, 'MM')) = :MES --TO_NUMBER(TO_CHAR(:P_FECHA_HASTA,'MM'))
    AND PR_ORDEN_DE_PAGO_REGISTRO.RUBRO_INTERNO = NVL(:P_RUBRO_INTERNO,PR_ORDEN_DE_PAGO_REGISTRO.RUBRO_INTERNO)
 GROUP BY  PR_ORDEN_DE_PAGO_REGISTRO.RUBRO_INTERNO, PR_ORDEN_DE_PAGO_REGISTRO.NUMERO_REGISTRO
	 ) PR_MES
